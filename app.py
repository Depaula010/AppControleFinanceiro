@app.route('/admin/setup-database', methods=['GET'])
def setup_database():
    """ 
    Cria/Recria a ESTRUTURA final do banco com Agendamentos e Transferências. 
    Execute PRIMEIRO.
    """
    if not engine: return "Erro: Banco não configurado.", 500

    # SEU NOVO SCRIPT DDL (Parte 1 - Com Agendamentos e Faturas)
    sql_script_ddl = """
    DROP TABLE IF EXISTS Agendamentos CASCADE;
    DROP TABLE IF EXISTS Transacoes CASCADE;
    DROP TABLE IF EXISTS Faturas CASCADE;
    DROP TABLE IF EXISTS Contas CASCADE;
    DROP TABLE IF EXISTS SubCategoria CASCADE;
    DROP TABLE IF EXISTS MacroCategoria CASCADE;
    DROP TABLE IF EXISTS GrupoCategoria CASCADE;
    DROP TABLE IF EXISTS Usuarios CASCADE;

    CREATE TABLE Usuarios (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome VARCHAR(255) NOT NULL,
        numero_whatsapp VARCHAR(50) NOT NULL UNIQUE,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE GrupoCategoria (
        id SERIAL PRIMARY KEY,
        nome_grupo VARCHAR(100) NOT NULL UNIQUE
    );

    CREATE TABLE MacroCategoria (
        id SERIAL PRIMARY KEY,
        grupo_id INT NOT NULL REFERENCES GrupoCategoria(id) ON DELETE RESTRICT,
        usuario_id INT REFERENCES Usuarios(id) ON DELETE CASCADE,
        nome_macro VARCHAR(255) NOT NULL,
        ordem_macro INT
    );

    CREATE TABLE SubCategoria (
        id SERIAL PRIMARY KEY,
        macro_id INT NOT NULL REFERENCES MacroCategoria(id) ON DELETE CASCADE,
        usuario_id INT REFERENCES Usuarios(id) ON DELETE CASCADE,
        nome_sub VARCHAR(255) NOT NULL,
        UNIQUE(macro_id, nome_sub, usuario_id)
    );

    CREATE TABLE Contas (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        usuario_id INT NOT NULL REFERENCES Usuarios(id) ON DELETE CASCADE,
        nome_conta VARCHAR(100) NOT NULL,
        tipo_conta VARCHAR(50) NOT NULL CHECK (tipo_conta IN ('Conta Corrente', 'Conta Poupança', 'Investimento', 'Cartão de Crédito', 'Dinheiro', 'Outro')),
        saldo_inicial NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
        dia_vencimento INT NULL CHECK (dia_vencimento >= 1 AND dia_vencimento <= 31),
        dia_fechamento INT NULL CHECK (dia_fechamento >= 1 AND dia_fechamento <= 31),
        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(usuario_id, nome_conta),
        CONSTRAINT chk_cartao_credito CHECK ( (tipo_conta = 'Cartão de Crédito') OR (dia_vencimento IS NULL AND dia_fechamento IS NULL) )
    );
    
    CREATE TABLE Faturas (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        conta_id INT NOT NULL REFERENCES Contas(id) ON DELETE CASCADE,
        data_vencimento DATE NOT NULL,
        data_fechamento DATE NOT NULL,
        status VARCHAR(20) NOT NULL DEFAULT 'Aberta' CHECK (status IN ('Aberta', 'Fechada', 'Paga')),
        UNIQUE(conta_id, data_vencimento)
    );

    CREATE TABLE Transacoes (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        usuario_id INT NOT NULL REFERENCES Usuarios(id) ON DELETE CASCADE,
        conta_id INT NOT NULL REFERENCES Contas(id) ON DELETE RESTRICT,
        subcategoria_id INT NOT NULL REFERENCES SubCategoria(id) ON DELETE RESTRICT,
        fatura_id INT NULL REFERENCES Faturas(id) ON DELETE SET NULL,
        transferencia_par_id INT NULL REFERENCES Transacoes(id) ON DELETE SET NULL, -- Novo campo
        descricao VARCHAR(255) NOT NULL,
        valor NUMERIC(15, 2) NOT NULL CHECK (valor >= 0), -- Mantendo valor positivo
        data_transacao DATE NOT NULL DEFAULT CURRENT_DATE,
        tipo_transacao VARCHAR(10) NOT NULL CHECK (tipo_transacao IN ('Renda', 'Despesa', 'Transferência')),
        consolidada BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE Agendamentos ( -- Nova Tabela
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        usuario_id INT NOT NULL REFERENCES Usuarios(id) ON DELETE CASCADE,
        conta_id INT NOT NULL REFERENCES Contas(id) ON DELETE CASCADE,
        subcategoria_id INT NOT NULL REFERENCES SubCategoria(id) ON DELETE RESTRICT,
        descricao VARCHAR(255) NOT NULL,
        valor_previsto NUMERIC(15, 2), 
        tipo_agendamento VARCHAR(20) NOT NULL CHECK (tipo_agendamento IN ('FIXO', 'PARCELADO', 'LEMBRETE_VARIAVEL')),
        periodicidade VARCHAR(20) NOT NULL CHECK (periodicidade IN ('DIARIA', 'SEMANAL', 'QUINZENAL', 'MENSAL', 'ANUAL')),
        data_inicio DATE NOT NULL,
        dia_execucao INT NOT NULL CHECK (dia_execucao >= 1 AND dia_execucao <= 31),
        total_parcelas INT,
        parcelas_executadas INT DEFAULT 0,
        notificar_antes_dias INT DEFAULT 3,
        ativo BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT chk_parcelado CHECK ( (tipo_agendamento = 'PARCELADO') OR (total_parcelas IS NULL AND parcelas_executadas = 0) )
    );

    -- Índices
    CREATE INDEX IF NOT EXISTS idx_macro_usuario_id ON MacroCategoria(usuario_id);
    CREATE INDEX IF NOT EXISTS idx_sub_usuario_id ON SubCategoria(usuario_id);
    CREATE INDEX IF NOT EXISTS idx_contas_usuario_id ON Contas(usuario_id);
    CREATE INDEX IF NOT EXISTS idx_faturas_conta_id ON Faturas(conta_id);
    CREATE INDEX IF NOT EXISTS idx_transacoes_usuario_id ON Transacoes(usuario_id);
    CREATE INDEX IF NOT EXISTS idx_transacoes_fatura_id ON Transacoes(fatura_id);
    CREATE INDEX IF NOT EXISTS idx_transacoes_transfer_par_id ON Transacoes(transferencia_par_id);
    CREATE INDEX IF NOT EXISTS idx_agendamentos_usuario_id ON Agendamentos(usuario_id);
    """
    
    try:
        with engine.connect() as conn:
            conn.execute(text(sql_script_ddl))
            conn.commit() 
        return "Estrutura final do banco (v9 com Agendamentos) criada/recriada com sucesso!", 200
    except Exception as e:
        try: 
            with engine.connect() as conn: conn.rollback()
        except: pass
        return f"Erro ao criar estrutura do banco: {e}", 500


