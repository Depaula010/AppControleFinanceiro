@app.route('/admin/setup-database', methods=['GET'])
def setup_database():
    """
    Cria/Recria a ESTRUTURA completa do banco com o novo schema normalizado.
    Execute PRIMEIRO.
    """
    if not engine:
        return "Erro: Conexão com o banco de dados não configurada.", 500

    # SEU NOVO SCRIPT DDL (Parte 1)
    sql_script_ddl = """
    DROP TABLE IF EXISTS Transacoes CASCADE;
    DROP TABLE IF EXISTS Contas CASCADE;
    DROP TABLE IF EXISTS SubCategoria CASCADE;
    DROP TABLE IF EXISTS MacroCategoria CASCADE;
    DROP TABLE IF EXISTS GrupoCategoria CASCADE;
    DROP TABLE IF EXISTS Usuarios CASCADE;

    CREATE TABLE Usuarios (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome VARCHAR(255) NOT NULL,
        numero_whatsapp VARCHAR(50) NOT NULL UNIQUE,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE GrupoCategoria (
        id SERIAL PRIMARY KEY,
        nome_grupo VARCHAR(100) NOT NULL UNIQUE
    );

    CREATE TABLE MacroCategoria (
        id SERIAL PRIMARY KEY,
        grupo_id INT NOT NULL REFERENCES GrupoCategoria(id) ON DELETE RESTRICT,
        usuario_id INT REFERENCES Usuarios(id) ON DELETE CASCADE, -- NULL para global
        nome_macro VARCHAR(255) NOT NULL,
        ordem_macro INT
    );

    CREATE TABLE SubCategoria (
        id SERIAL PRIMARY KEY,
        macro_id INT NOT NULL REFERENCES MacroCategoria(id) ON DELETE CASCADE,
        usuario_id INT REFERENCES Usuarios(id) ON DELETE CASCADE, -- NULL para global
        nome_sub VARCHAR(255) NOT NULL,
        UNIQUE(macro_id, nome_sub, usuario_id) -- Evita duplicatas por usuário ou global
    );

    CREATE TABLE Contas (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        usuario_id INT NOT NULL REFERENCES Usuarios(id) ON DELETE CASCADE,
        nome_conta VARCHAR(100) NOT NULL,
        tipo_conta VARCHAR(50) CHECK (tipo_conta IN ('Conta Corrente', 'Conta Poupança', 'Investimento', 'Cartão de Crédito', 'Dinheiro', 'Outro')),
        saldo_inicial NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
         UNIQUE(usuario_id, nome_conta) -- Evita contas duplicadas para o mesmo usuário
    );

    CREATE TABLE Transacoes (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        usuario_id INT NOT NULL REFERENCES Usuarios(id) ON DELETE CASCADE,
        conta_id INT NOT NULL REFERENCES Contas(id) ON DELETE RESTRICT,
        subcategoria_id INT REFERENCES SubCategoria(id) ON DELETE RESTRICT, -- Alterado para não permitir nulo inicialmente
        descricao VARCHAR(255) NOT NULL,
        valor NUMERIC(15, 2) NOT NULL CHECK (valor >= 0), -- Permite valor zero para transferências? Ou deve ser > 0?
        data_transacao DATE NOT NULL DEFAULT CURRENT_DATE,
        tipo_transacao VARCHAR(10) NOT NULL CHECK (tipo_transacao IN ('Renda', 'Despesa', 'Transferência')),
        consolidada BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
    );

    -- Índices
    CREATE INDEX IF NOT EXISTS idx_macro_grupo_id ON MacroCategoria(grupo_id);
    CREATE INDEX IF NOT EXISTS idx_sub_macro_id ON SubCategoria(macro_id);
    CREATE INDEX IF NOT EXISTS idx_macro_usuario_id ON MacroCategoria(usuario_id);
    CREATE INDEX IF NOT EXISTS idx_sub_usuario_id ON SubCategoria(usuario_id);
    CREATE INDEX IF NOT EXISTS idx_contas_usuario_id ON Contas(usuario_id);
    CREATE INDEX IF NOT EXISTS idx_transacoes_usuario_id ON Transacoes(usuario_id);
    CREATE INDEX IF NOT EXISTS idx_transacoes_conta_id ON Transacoes(conta_id);
    CREATE INDEX IF NOT EXISTS idx_transacoes_subcategoria_id ON Transacoes(subcategoria_id);
    """
    
    try:
        with engine.connect() as conn:
            conn.execute(text(sql_script_ddl))
            conn.commit() 
        return "Estrutura normalizada do banco criada/recriada com sucesso!", 200
    except Exception as e:
        # Tenta reverter em caso de erro parcial
        try: 
            with engine.connect() as conn: conn.rollback()
        except: pass # Ignora erros no rollback
        return f"Erro ao criar estrutura do banco: {e}", 500


