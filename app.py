@app.route('/webhook-automate', methods=['POST'])
def handle_automate_webhook():
    if not engine or not model:
        return jsonify({"status": "erro", "mensagem": "Serviço não configurado"}), 500

    try:
        data = request.json
        texto_notificacao = data.get('texto')
        if not texto_notificacao: return jsonify({"status": "erro", "mensagem": "Chave 'texto' faltando"}), 400
        print(f"[AUTOMATE] Recebido: {texto_notificacao}")

        # 1. CHAMANDO O GEMINI (para extrair e classificar Renda/Despesa)
        prompt_para_gemini = f"""
        Analise a notificação: "{texto_notificacao}"
        Retorne APENAS JSON com: "valor_decimal", "descricao_bruta", "tipo_fluxo" ("Renda" ou "Despesa").
        Ex: {{"valor_decimal": 45.00, "descricao_bruta": "PADARIA", "tipo_fluxo": "Despesa"}}
        """
        response = model.generate_content(prompt_para_gemini)
        json_response_text = response.text.strip().replace("```json", "").replace("```", "")
        transacao_gemini = json.loads(json_response_text)
        print(f"[GEMINI] Resposta: {json_response_text}")
        
        # Mapeia tipo_fluxo para tipo_transacao do banco ('Renda'/'Despesa')
        tipo_transacao_db = transacao_gemini.get('tipo_fluxo', 'Despesa') # Default para Despesa

        # 2. IDENTIFICAÇÃO (SIMPLIFICADA)
        usuario_id_fixo = 1 # Assumindo que você é sempre o usuário 1
        conta_id_fixa = 1   # Assumindo conta 'Banco Inter' (precisaria de lógica para identificar a conta)
        
        # 3. ENCONTRAR SUBCATEGORIA "OUTROS" APROPRIADA
        nome_macro_outros = 'Receitas Gerais' if tipo_transacao_db == 'Renda' else 'Despesas Gerais'
        
        sql_find_subcat_outros = text("""
            SELECT s.id 
            FROM SubCategoria s
            JOIN MacroCategoria m ON s.macro_id = m.id
            WHERE m.nome_macro = :nome_macro 
              AND s.nome_sub = 'Outros' 
              AND s.usuario_id IS NULL -- Busca o template global
            LIMIT 1
        """)
        id_subcategoria_outros = None
        with engine.connect() as conn:
            result = conn.execute(sql_find_subcat_outros, {"nome_macro": nome_macro_outros})
            id_subcategoria_outros = result.scalar_one_or_none()

        if id_subcategoria_outros is None:
             print(f"ERRO CRÍTICO: Não foi possível encontrar a SubCategoria global 'Outros' para a Macro '{nome_macro_outros}'")
             return jsonify({"status": "erro", "mensagem": "Erro interno: Categoria 'Outros' não encontrada"}), 500

        # 4. SALVANDO NO BANCO DE DADOS
        sql_insert = text("""
        INSERT INTO Transacoes (usuario_id, conta_id, subcategoria_id, descricao, valor, tipo_transacao, data_transacao)
        VALUES (:uid, :cid, :scid, :desc, :val, :tipo, CURRENT_DATE) 
        """) 
        
        with engine.connect() as conn:
            conn.execute(sql_insert, {
                "uid": usuario_id_fixo,
                "cid": conta_id_fixa, 
                "scid": id_subcategoria_outros, 
                "desc": transacao_gemini['descricao_bruta'],
                "val": transacao_gemini['valor_decimal'],
                "tipo": tipo_transacao_db 
            })
            conn.commit()
        
        print(f"[DATABASE] Transação salva com sucesso (Usuário: {usuario_id_fixo}, Conta: {conta_id_fixa}, SubCat: {id_subcategoria_outros})!")

        return jsonify({"status": "sucesso", "transacao_salva": transacao_gemini}), 200

    # Captura erros específicos do banco de dados também
    except sqlalchemy_exc.SQLAlchemyError as db_err:
        print(f"Erro de Banco de Dados no webhook do Automate: {db_err}")
        return jsonify({"status": "erro", "mensagem": f"Erro de Banco de Dados: {db_err}"}), 500
    except Exception as e:
        print(f"Erro geral no webhook do Automate: {e}")
        return jsonify({"status": "erro", "mensagem": str(e)}), 500


