import os
import json
from flask import Flask, request, jsonify
import google.generativeai as genai
from sqlalchemy import create_engine, text

# ========= 1. CONFIGURAÇÃO INICIAL =========

app = Flask(__name__)

# Carregar as "senhas" (Variáveis de Ambiente) que salvamos no Render
try:
    GEMINI_API_KEY = os.environ['GEMINI_API_KEY']
    DATABASE_URL = os.environ['DATABASE_URL']
except KeyError:
    print("Erro: Variáveis de Ambiente (GEMINI_API_KEY ou DATABASE_URL) não encontradas.")
    # Se não achar as chaves, o app não deve funcionar
    GEMINI_API_KEY = None
    DATABASE_URL = None

# Configurar o cliente do Gemini
if GEMINI_API_KEY:
    genai.configure(api_key=GEMINI_API_KEY)
    model = genai.GenerativeModel('gemini-pro') # Usando o modelo mais rápido

# Configurar a conexão com o Banco de Dados
if DATABASE_URL:
    # A URL do Render pode vir como 'postgres://', mas SQLAlchemy prefere 'postgresql://'
    if DATABASE_URL.startswith("postgres://"):
        DATABASE_URL = DATABASE_URL.replace("postgres://", "postgresql://", 1)
    
    engine = create_engine(DATABASE_URL)
else:
    engine = None

# ========= 2. ROTA PARA CRIAR O BANCO DE DADOS (Vamos usar 1 vez) =========

@app.route('/admin/setup-database', methods=['GET'])
def setup_database():
    """
    Esta é uma rota administrativa. 
    Vamos acessá-la UMA VEZ pelo navegador para criar nossas tabelas.
    """
    if not engine:
        return "Erro: Conexão com o banco de dados não configurada.", 500

    # Script SQL que você aprovou
    sql_script = """
    CREATE TYPE tipo_conta AS ENUM ('Conta Corrente', 'Cartão de Crédito', 'Dinheiro Físico', 'Investimento');
    CREATE TYPE tipo_fluxo AS ENUM ('RECEITA', 'DESPESA');

    CREATE TABLE IF NOT EXISTS Usuarios (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome VARCHAR(255) NOT NULL,
        numero_whatsapp VARCHAR(50) NOT NULL UNIQUE,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS Contas (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_usuario INT NOT NULL REFERENCES Usuarios(id) ON DELETE CASCADE,
        nome VARCHAR(255) NOT NULL,
        tipo tipo_conta NOT NULL,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(id_usuario, nome)
    );

    CREATE TABLE IF NOT EXISTS Categorias (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_usuario INT NOT NULL REFERENCES Usuarios(id) ON DELETE CASCADE,
        nome VARCHAR(255) NOT NULL,
        tipo tipo_fluxo NOT NULL,
        eh_essencial BOOLEAN NOT NULL DEFAULT FALSE,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(id_usuario, nome)
    );

    CREATE TABLE IF NOT EXISTS Transacoes (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_conta INT NOT NULL REFERENCES Contas(id) ON DELETE CASCADE,
        id_categoria INT REFERENCES Categorias(id) ON DELETE SET NULL, 
        descricao VARCHAR(500) NOT NULL,
        valor NUMERIC(12, 2) NOT NULL CHECK (valor > 0),
        tipo tipo_fluxo NOT NULL,
        data TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
    );

    CREATE INDEX IF NOT EXISTS idx_transacoes_conta ON Transacoes(id_conta);
    CREATE INDEX IF NOT EXISTS idx_transacoes_categoria ON Transacoes(id_categoria);
    """
    
    try:
        with engine.connect() as conn:
            conn.execute(text("DROP TYPE IF EXISTS tipo_conta CASCADE;"))
            conn.execute(text("DROP TYPE IF EXISTS tipo_fluxo CASCADE;"))
            conn.execute(text(sql_script))
            conn.commit() # Confirma as mudanças
        return "Tabelas criadas com sucesso!", 200
    except Exception as e:
        return f"Erro ao criar tabelas: {e}", 500

