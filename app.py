@app.route('/webhook-automate', methods=['POST'])
def handle_automate_webhook():
    if not engine or not model:
        return jsonify({"status": "erro", "mensagem": "Serviço não configurado"}), 500

    try:
        data = request.json
        texto_notificacao = data.get('texto')
        if not texto_notificacao: return jsonify({"status": "erro", "mensagem": "Chave 'texto' faltando"}), 400
        print(f"[AUTOMATE] Recebido: {texto_notificacao}")

        # 1. CHAMANDO O GEMINI
        prompt_para_gemini = f"""
        Analise a notificação: "{texto_notificacao}"
        Retorne APENAS JSON com: "valor_decimal", "descricao_bruta", "tipo_fluxo" ("RECEITA" ou "DESPESA").
        Ex: {{"valor_decimal": 45.00, "descricao_bruta": "PADARIA", "tipo_fluxo": "DESPESA"}}
        """
        response = model.generate_content(prompt_para_gemini)
        json_response_text = response.text.strip().replace("```json", "").replace("```", "")
        transacao_gemini = json.loads(json_response_text)
        print(f"[GEMINI] Resposta: {json_response_text}")

        # 2. DECISÃO DE CATEGORIA E CONTA (SIMPLIFICADA)
        id_conta_fixa = 1   # ID da conta 'Banco Inter' (Primeira conta criada)
        
        # Encontra o ID da SubCategoria "Outros" apropriada (Receita ou Despesa)
        # Assumindo que a Macro "Receitas Gerais" é ID 18 e "Despesas Gerais" é ID 17
        id_macro_geral = 18 if transacao_gemini['tipo_fluxo'] == 'RECEITA' else 17
        
        # Precisamos buscar o ID da subcategoria "Outros" dentro dessa macro
        sql_find_subcat = text("SELECT id FROM SubCategoria WHERE macro_id = :macro_id AND nome_sub = 'Outros'")
        id_subcategoria_outros = None
        with engine.connect() as conn:
            result = conn.execute(sql_find_subcat, {"macro_id": id_macro_geral})
            id_subcategoria_outros = result.scalar_one_or_none()

        if id_subcategoria_outros is None:
             print(f"ERRO CRÍTICO: Não foi possível encontrar a SubCategoria 'Outros' para a Macro ID {id_macro_geral}")
             # Poderia usar um ID fixo de fallback aqui ou retornar erro
             id_subcategoria_outros = 1 # Fallback MUITO arriscado, apenas para não quebrar agora

        # 3. SALVANDO NO BANCO DE DADOS
        sql_insert = text("""
        INSERT INTO Transacoes (id_conta, id_subcategoria, descricao, valor, tipo)
        VALUES (:id_conta, :id_subcategoria, :descricao, :valor, :tipo) 
        """) # Não precisa mais do CAST ::tipo_fluxo pois tipo agora é VARCHAR(10)
        
        with engine.connect() as conn:
            conn.execute(sql_insert, {
                "id_conta": id_conta_fixa, 
                "id_subcategoria": id_subcategoria_outros, 
                "descricao": transacao_gemini['descricao_bruta'],
                "valor": transacao_gemini['valor_decimal'],
                "tipo": transacao_gemini['tipo_fluxo'] 
            })
            conn.commit()
        
        print(f"[DATABASE] Transação salva com sucesso na conta {id_conta_fixa}!")

        return jsonify({"status": "sucesso", "transacao_salva": transacao_gemini}), 200

    except Exception as e:
        print(f"Erro no webhook do Automate: {e}")
        return jsonify({"status": "erro", "mensagem": str(e)}), 500

