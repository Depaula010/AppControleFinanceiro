@app.route('/admin/setup-database', methods=['GET'])
def setup_database():
    """
    Cria a estrutura COMPLETA do banco, incluindo as novas tabelas de categorias
    e ajustando a tabela Transacoes.
    """
    if not engine:
        return "Erro: Conexão com o banco de dados não configurada.", 500

    # Script SQL para criar TODA a estrutura
    sql_script_ddl = """
    -- Remove tipos antigos se existirem
    DROP TYPE IF EXISTS tipo_conta CASCADE;
    DROP TYPE IF EXISTS tipo_fluxo CASCADE;
    
    -- Remove tabelas antigas se existirem (na ordem correta)
    DROP TABLE IF EXISTS Transacoes CASCADE;
    DROP TABLE IF EXISTS SubCategoria CASCADE;
    DROP TABLE IF EXISTS MacroCategoria CASCADE;
    DROP TABLE IF EXISTS GrupoCategoria CASCADE;
    DROP TABLE IF EXISTS Contas CASCADE;
    DROP TABLE IF EXISTS Usuarios CASCADE;

    -- Recria tipos necessários
    CREATE TYPE tipo_conta AS ENUM ('Conta Corrente', 'Cartão de Crédito', 'Dinheiro Físico', 'Investimento');

    -- Criação das tabelas
    CREATE TABLE Usuarios (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome VARCHAR(255) NOT NULL,
        numero_whatsapp VARCHAR(50) NOT NULL UNIQUE,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE Contas (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_usuario INT NOT NULL REFERENCES Usuarios(id) ON DELETE CASCADE,
        nome VARCHAR(255) NOT NULL,
        tipo tipo_conta NOT NULL,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(id_usuario, nome)
    );
    
    -- === NOVAS TABELAS DE CATEGORIA ===
    CREATE TABLE GrupoCategoria (
        id SERIAL PRIMARY KEY,
        nome_grupo VARCHAR(100) NOT NULL UNIQUE
    );

    CREATE TABLE MacroCategoria (
        id SERIAL PRIMARY KEY,
        grupo_id INT NOT NULL REFERENCES GrupoCategoria(id) ON DELETE RESTRICT,
        nome_macro VARCHAR(255) NOT NULL,
        ordem_macro INT -- Nullable, pode não ter ordem
    );

    CREATE TABLE SubCategoria (
        id SERIAL PRIMARY KEY,
        macro_id INT NOT NULL REFERENCES MacroCategoria(id) ON DELETE CASCADE,
        nome_sub VARCHAR(255) NOT NULL,
        -- Garante que não haja subcategorias repetidas dentro da mesma macro
        UNIQUE(macro_id, nome_sub) 
    );
    -- === FIM NOVAS TABELAS DE CATEGORIA ===

    CREATE TABLE Transacoes (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_conta INT NOT NULL REFERENCES Contas(id) ON DELETE CASCADE,
        
        -- AGORA LIGA COM A SUBCATEGORIA!
        id_subcategoria INT REFERENCES SubCategoria(id) ON DELETE SET NULL, 
        
        descricao VARCHAR(500) NOT NULL,
        valor NUMERIC(12, 2) NOT NULL CHECK (valor > 0),
        
        -- Precisamos saber se é Receita/Despesa na própria transação
        -- Poderia derivar do GrupoCategoria, mas deixamos explícito aqui
        tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('RECEITA', 'DESPESA')), 
        
        data TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
    );

    -- Índices
    CREATE INDEX IF NOT EXISTS idx_macro_grupo_id ON MacroCategoria(grupo_id);
    CREATE INDEX IF NOT EXISTS idx_sub_macro_id ON SubCategoria(macro_id);
    CREATE INDEX IF NOT EXISTS idx_transacoes_conta ON Transacoes(id_conta);
    CREATE INDEX IF NOT EXISTS idx_transacoes_subcategoria ON Transacoes(id_subcategoria);
    """
    
    try:
        with engine.connect() as conn:
            conn.execute(text(sql_script_ddl))
            conn.commit() 
        return "Estrutura completa do banco criada/recriada com sucesso!", 200
    except Exception as e:
        return f"Erro ao criar estrutura do banco: {e}", 500


